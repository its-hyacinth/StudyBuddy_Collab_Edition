<?php
declare(strict_types=1);

require_once __DIR__ . '/../includes/postgres_bootstrap.php';

function db_setting(string $name, string $default): string {
    $value = getenv($name);
    if ((!is_string($value) || $value === '') && isset($_ENV[$name]) && is_string($_ENV[$name])) $value = $_ENV[$name];
    if ((!is_string($value) || $value === '') && isset($_SERVER[$name]) && is_string($_SERVER[$name])) $value = $_SERVER[$name];
    return (!is_string($value) || $value === '') ? $default : $value;
}

function sb_database_url(): string {
    foreach (['POSTGRES_URL_NON_POOLING', 'DATABASE_URL_UNPOOLED', 'POSTGRES_URL', 'DATABASE_URL'] as $name) {
        $value = db_setting($name, '');
        if (preg_match('#^postgres(?:ql)?://#i', $value)) return $value;
    }
    return '';
}

function sb_sql(string $sql): string {
    if (!defined('SB_DB_DRIVER') || SB_DB_DRIVER !== 'pgsql') return $sql;
    $sql = preg_replace('/\bUNSIGNED\b/i', '', $sql) ?? $sql;
    $sql = preg_replace('/\bAUTO_INCREMENT\b/i', 'GENERATED BY DEFAULT AS IDENTITY', $sql) ?? $sql;
    $sql = preg_replace('/\bTINYINT\(\d+\)/i', 'SMALLINT', $sql) ?? $sql;
    $sql = preg_replace('/\bLONGTEXT\b/i', 'TEXT', $sql) ?? $sql;
    $sql = preg_replace('/\bDATETIME\b/i', 'TIMESTAMP', $sql) ?? $sql;
    $sql = preg_replace('/\s+ENGINE\s*=\s*InnoDB\b/i', '', $sql) ?? $sql;
    $sql = preg_replace('/\s+ON UPDATE CURRENT_TIMESTAMP/i', '', $sql) ?? $sql;
    $sql = preg_replace("/ENUM\((?:'[^']*'\s*,\s*)*'[^']*'\)/i", 'VARCHAR(30)', $sql) ?? $sql;
    $sql = preg_replace('/DATE_ADD\(\s*NOW\(\)\s*,\s*INTERVAL\s+(\d+)\s+MINUTE\s*\)/i', "(NOW() + INTERVAL '$1 minutes')", $sql) ?? $sql;
    $sql = preg_replace('/DATE_ADD\(\s*NOW\(\)\s*,\s*INTERVAL\s+(\d+)\s+DAY\s*\)/i', "(NOW() + INTERVAL '$1 days')", $sql) ?? $sql;
    $sql = preg_replace('/NOW\(\)\s*-\s*INTERVAL\s+(\d+)\s+DAY\b/i', "NOW() - INTERVAL '$1 days'", $sql) ?? $sql;
    $sql = preg_replace('/NOW\(\)\s*-\s*INTERVAL\s+(\d+)\s+MINUTE\b/i', "NOW() - INTERVAL '$1 minutes'", $sql) ?? $sql;
    $sql = preg_replace(
        '/ON DUPLICATE KEY UPDATE\s+state_value\s*=\s*VALUES\(\s*state_value\s*\)/i',
        'ON CONFLICT (user_id, state_key) DO UPDATE SET state_value = EXCLUDED.state_value',
        $sql
    ) ?? $sql;
    if (preg_match('/INSERT INTO google_connections/i', $sql)) {
        $sql = preg_replace(
            '/ON DUPLICATE KEY UPDATE\s+.*/is',
            'ON CONFLICT (user_id) DO UPDATE SET google_email = EXCLUDED.google_email, refresh_token = EXCLUDED.refresh_token, access_token = EXCLUDED.access_token, access_expires_at = EXCLUDED.access_expires_at, scopes = EXCLUDED.scopes',
            $sql
        ) ?? $sql;
    }
    return $sql;
}

function sb_is_duplicate(PDOException $error): bool {
    $code = (string)$error->getCode();
    return $code === '23000' || $code === '23505';
}

function sb_last_insert_id(PDO $pdo): int {
    $id = (int)$pdo->lastInsertId();
    if ($id > 0) return $id;
    if (defined('SB_DB_DRIVER') && SB_DB_DRIVER === 'pgsql') {
        $value = $pdo->query('SELECT lastval()');
        return $value ? (int)$value->fetchColumn() : 0;
    }
    return $id;
}

class StudyBuddyPdo extends PDO {
    public function prepare(string $query, array $options = []): PDOStatement|false {
        return parent::prepare(sb_sql($query), $options);
    }

    public function exec(string $statement): int|false {
        return parent::exec(sb_sql($statement));
    }

    public function query(string $query, ?int $fetchMode = null, mixed ...$fetchModeArgs): PDOStatement|false {
        $query = sb_sql($query);
        if ($fetchMode === null) return parent::query($query);
        return parent::query($query, $fetchMode, ...$fetchModeArgs);
    }
}

// Hosted sign-in uses the Postgres database connected to the Vercel project.
function db(): PDO {
    static $pdo = null;
    if ($pdo instanceof PDO) return $pdo;
    $options = [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    ];
    $url = sb_database_url();
    if ($url !== '') {
        if (!defined('SB_DB_DRIVER')) define('SB_DB_DRIVER', 'pgsql');
        $parts = parse_url($url);
        if ($parts === false || empty($parts['host'])) {
            throw new PDOException('The hosted database address is invalid.');
        }
        $query = [];
        parse_str((string)($parts['query'] ?? ''), $query);
        $ssl = is_string($query['sslmode'] ?? null) && $query['sslmode'] !== '' ? $query['sslmode'] : 'require';
        $dsn = 'pgsql:host=' . $parts['host']
            . ';port=' . (int)($parts['port'] ?? 5432)
            . ';dbname=' . ltrim((string)($parts['path'] ?? ''), '/')
            . ';sslmode=' . $ssl;
        $options[PDO::ATTR_EMULATE_PREPARES] = true;
        $pdo = new StudyBuddyPdo(
            $dsn,
            rawurldecode((string)($parts['user'] ?? '')),
            rawurldecode((string)($parts['pass'] ?? '')),
            $options
        );
        $pdo->exec("SET TIME ZONE 'UTC'");
        sb_ensure_postgres($pdo);
        return $pdo;
    }
    if (!defined('SB_DB_DRIVER')) define('SB_DB_DRIVER', 'mysql');
    $options[PDO::ATTR_EMULATE_PREPARES] = false;
    $dsn = 'mysql:host=' . db_setting('SB_DB_HOST', '127.0.0.1')
        . ';dbname=' . db_setting('SB_DB_NAME', 'Studybuddy')
        . ';charset=utf8mb4';
    $pdo = new StudyBuddyPdo($dsn, db_setting('SB_DB_USER', 'root'), db_setting('SB_DB_PASS', ''), $options);
    $pdo->exec("SET time_zone = '+00:00'");
    if (!$pdo->query("SHOW COLUMNS FROM notifications LIKE 'target_url'")->fetch()) {
        $pdo->exec('ALTER TABLE notifications ADD target_url VARCHAR(1000) NULL AFTER body');
    }
    return $pdo;
}
